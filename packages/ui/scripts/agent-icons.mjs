#!/usr/bin/env node
// Generates src/components/agent-icons.generated.ts from the SVG files in
// assets/agents/. The files are the source of truth — they are what the sites
// serve at /agents/ and what a README links to — so the component's markup is
// derived from them rather than hand-copied, and a re-import is a re-run.
//
//   node scripts/agent-icons.mjs          # rewrite the generated module
//   node scripts/agent-icons.mjs --check  # exit 1 if it is out of date
//
// agent-icon.test.ts runs the same check under `vitest`, so CI catches a file
// added to assets/agents/ without a re-run.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
export const ASSETS_DIR = join(root, 'assets/agents');
export const OUT_FILE = join(root, 'src/components/agent-icons.generated.ts');

/** Display names. Every base file in assets/agents/ needs one, or generation fails. */
const NAMES = {
  aider: 'Aider',
  anthropic: 'Anthropic',
  antigravity: 'Antigravity',
  claude: 'Claude',
  cline: 'Cline',
  codex: 'Codex',
  copilot: 'GitHub Copilot',
  cursor: 'Cursor',
  gemini: 'Gemini',
  grok: 'Grok',
  kilo: 'Kilo Code',
  mistral: 'Mistral',
  ollama: 'Ollama',
  openclaude: 'OpenClaude',
  opencode: 'opencode',
};

/**
 * Marks whose file is unusable as a component, with the markup to use instead.
 * aider.svg is a 930 KB trace (400 paths in a 2048 viewBox) — right as a file to
 * link, wrong to bundle — so the component carries Studio's compact glyph.
 */
const OVERRIDES = {
  aider: {
    mono: '<path d="M12 2L2 22h4.5l2.1-4.5h6.8l2.1 4.5H22L12 2zm0 5.2l2.4 5.3H9.6L12 7.2zM4 4h4v2H4V4zm12 0h4v2h-4V4z"/>',
    color: '#0CDD79',
  },
};

/** `-color` files that are not a brand colour: grok's is white-on-dark, so grok stays monochrome. */
const NOT_A_BRAND_COLOR = new Set(['grok']);

const inner = (svg) =>
  svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/><\/(path|rect|circle)>/g, '/>')
    .trim();

const rootFill = (svg) => /<svg[^>]*\sfill="([^"]+)"/.exec(svg)?.[1];
const onlyFill = (svg) => {
  const fills = [...new Set([...svg.matchAll(/fill="([^"]+)"/g)].map((m) => m[1]))];
  return fills.length === 1 ? fills[0] : undefined;
};

/** Strips child fills so the mark paints with the root's `fill`. */
const monochrome = (markup) => markup.replace(/\sfill="[^"]*"/g, '');

export function buildAgentIconModule(dir = ASSETS_DIR) {
  const files = readdirSync(dir).filter((f) => f.endsWith('.svg'));
  const read = (f) => readFileSync(join(dir, f), 'utf8');
  const ids = files.filter((f) => !/-(color|white|ink)\.svg$/.test(f)).map((f) => f.slice(0, -4));

  const entries = ids.sort().map((id) => {
    const name = NAMES[id];
    if (!name) throw new Error(`assets/agents/${id}.svg has no display name in NAMES`);
    const file = (variant) => `${id}${variant ? `-${variant}` : ''}.svg`;
    const variants = files
      .filter((f) => f === file() || f.startsWith(`${id}-`))
      .map((f) => f.slice(0, -4))
      .sort();
    const base = read(file());

    if (OVERRIDES[id]) return { id, name, ...OVERRIDES[id], files: variants };

    // antigravity: a multi-colour wash clipped to a silhouette. The colour form is
    // the file itself; the mono form is the silhouette (the mask's own path).
    if (/<mask/.test(base)) {
      const silhouette = /<mask[^>]*>\s*<path d="([^"]+)"/.exec(base)?.[1];
      if (!silhouette) throw new Error(`${file()}: mask without a silhouette path`);
      // Its ids are upstream's `-R0`; swap them for a placeholder AgentIcon scopes per instance.
      const art = inner(base).replace(/-R0\b/g, '-__UID__');
      return { id, name, mono: `<path d="${silhouette}"/>`, art, files: variants };
    }

    const colorFile = files.includes(file('color')) ? read(file('color')) : base;
    const fill = rootFill(colorFile) ?? onlyFill(colorFile);
    const color =
      !NOT_A_BRAND_COLOR.has(id) && fill && fill !== 'currentColor'
        ? fill.toUpperCase()
        : undefined;
    return { id, name, mono: monochrome(inner(base)), color, files: variants };
  });

  const body = entries
    .map((e) => {
      const fields = [
        `name: ${JSON.stringify(e.name)}`,
        e.color ? `color: ${JSON.stringify(e.color)}` : undefined,
        `mono: ${JSON.stringify(e.mono)}`,
        e.art ? `art: ${JSON.stringify(e.art)}` : undefined,
        `files: ${JSON.stringify(e.files)}`,
      ].filter(Boolean);
      return `  ${e.id}: {\n${fields.map((f) => `    ${f},`).join('\n')}\n  },`;
    })
    .join('\n');

  return `// GENERATED by scripts/agent-icons.mjs from assets/agents/*.svg — do not edit.
// Re-run \`node scripts/agent-icons.mjs\` after changing a file there.

export const AGENT_ICON_DATA = {
${body}
} as const satisfies Record<string, AgentIconData>;

export type AgentIconData = {
  /** Display name, used as the accessible label. */
  readonly name: string;
  /** The brand colour; absent for monochrome brands, which paint with currentColor. */
  readonly color?: string;
  /** Single-colour markup on a 24x24 viewBox, painted by the root svg's fill. */
  readonly mono: string;
  /** Self-coloured artwork, for marks a single fill cannot express (antigravity). */
  readonly art?: string;
  /** Every file for this agent in assets/agents/, without the .svg extension. */
  readonly files: readonly string[];
};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = buildAgentIconModule();
  if (process.argv.includes('--check')) {
    const current = readFileSync(OUT_FILE, 'utf8');
    if (current !== next) {
      console.error('agent-icons.generated.ts is stale — run `node scripts/agent-icons.mjs`');
      process.exit(1);
    }
  } else {
    writeFileSync(OUT_FILE, next);
  }
}
